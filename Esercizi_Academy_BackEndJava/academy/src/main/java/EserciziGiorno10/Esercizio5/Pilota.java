package EserciziGiorno10.Esercizio5;

public class Pilota{
    private String nome;
    private Auto macchina;

    public Pilota(String nome, Auto macchina) {
        this.nome = nome;
        this.macchina = macchina;
    }

    public String getNome() {
        return nome;
    }

    public Auto getMacchina() {
        return macchina;
    }

    
}
