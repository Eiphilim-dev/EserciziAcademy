package EserciziGiorno5.Esercizio11;

public class Ordinamento {
    public static void main(String[] args) {
        int num1 = 3;
        int num2 = 4;
        int num3 = 5;

        if((num1 <= num2) && (num2 <= num3)){
            System.out.println("Sono ordinati");
        } else {
            System.out.println("Non sono ordinati");
        }
        
    }
}
