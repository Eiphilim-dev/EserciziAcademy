package EserciziGiorno5.Esercizio7;

public class Somma {
    public static void main(String[] args) {
        int num1 = 30;
        int num2 = 35;
        int somma = num1 + num2;

        if (somma > 100) {
            System.out.println("La somma dei numeri: " + num1 + " e " + num2 + "è maggiore di 100");
        } else {
            System.out.println("La somma dei numeri non è maggiore di 100");
        }
    }
}
