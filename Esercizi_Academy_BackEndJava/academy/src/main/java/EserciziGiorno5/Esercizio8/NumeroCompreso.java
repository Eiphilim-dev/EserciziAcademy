package EserciziGiorno5.Esercizio8;

public class NumeroCompreso {
    public static void main(String[] args) {
        int numero = 12;
        if (numero >= 0 && numero <= 10) {
            System.out.println("Il numero è compreso tra 1 a 10");
        } else {
            System.out.println("Errore".toUpperCase());
        }
    }
}
